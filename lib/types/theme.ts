/**
 * Theme-related types
 * Shared theme types across the application
 */

/**
 * Theme mode type (re-exported from config for convenience)
 */
export type ThemeMode = 'light' | 'dark' | 'system';

/**
 * Theme variant for components
 */
export type ThemeVariant = 'primary' | 'secondary' | 'accent' | 'success' | 'warning' | 'error' | 'info';

/**
 * Theme size scale
 */
export type ThemeSize = 'xs' | 'sm' | 'md' | 'lg' | 'xl';
